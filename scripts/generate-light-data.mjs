#!/usr/bin/env node
/**
 * Emits the *light* data the landing / dashboard need, so those routes never
 * download the 220 KB skill manifest or the 120 KB sound manifest just to
 * render a headline and a marquee.
 *
 *   src/data/toolkitStats.ts   — lightweight counters for landing and dashboard
 */
import fs from "node:fs";
import { build } from "esbuild";

async function loadModule(entry) {
  const out = await build({
    entryPoints: [entry],
    bundle: true,
    format: "esm",
    platform: "node",
    write: false,
  });
  const code = out.outputFiles[0].text;
  return import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
}

const { ALL_SKILLS_MANIFEST } = await loadModule("src/data/skillsManifest.ts");
const { ALL_BRAND_DESIGNS_MANIFEST } = await loadModule("src/data/skillsManifest.ts");
const { ALL_SOUND_RECIPES_MANIFEST } = await loadModule("src/data/soundsManifest.ts");
const { PERSIAN_FONT_CATALOG } = await loadModule("src/data/persianFontsCatalog.ts");
const { REGISTRY_FILES } = await loadModule("src/data/registryFiles.ts");

/* کتابخانه طراحی‌شده روی ۲۰۰ رسیپی قدیمی سوار می‌شود؛ شمارنده باید جمعشان باشد */
const DESIGNED_SOUND_COUNT = (
  fs.readFileSync("src/data/soundLibrary.ts", "utf8").match(/^ {2}s\(/gm) || []
).length;
const TOTAL_SOUNDS = ALL_SOUND_RECIPES_MANIFEST.length + DESIGNED_SOUND_COUNT;

const sourceTotal = REGISTRY_FILES.reduce((a, r) => a + r.sourceFiles, 0);
const fileTotal = REGISTRY_FILES.reduce((a, r) => a + r.totalFiles, 0);
const tsxTotal = REGISTRY_FILES.reduce(
  (a, r) => a + r.files.filter(([p]) => p.endsWith(".tsx")).length,
  0
);

const stats = `/**
 * AUTO-GENERATED by scripts/generate-light-data.mjs — do not edit by hand.
 * Counters below are measured by walking the vendored toolkit.
 */
export const TOOLKIT_STATS = {
  skills: ${ALL_SKILLS_MANIFEST.length},
  brands: ${ALL_BRAND_DESIGNS_MANIFEST.length},
  sounds: ${TOTAL_SOUNDS},
  fonts: ${PERSIAN_FONT_CATALOG.length},
  banks: 18,
  components: ${sourceTotal},
  componentFiles: ${fileTotal},
  tsxFiles: ${tsxTotal},
  registries: ${JSON.stringify(
    REGISTRY_FILES.map((r) => ({
      id: r.id,
      label: r.label,
      total: r.totalFiles,
      source: r.sourceFiles,
    })),
    null,
    2
  ).replace(/\n/g, "\n  ")},
} as const;

`;

fs.writeFileSync("src/data/toolkitStats.ts", stats);

console.log(
  `✅ stats: ${ALL_SKILLS_MANIFEST.length} skills · ${ALL_BRAND_DESIGNS_MANIFEST.length} brands · ${TOTAL_SOUNDS} sounds · ${PERSIAN_FONT_CATALOG.length} fonts`
);
console.log(`✅ registry: ${sourceTotal} source / ${fileTotal} files / ${tsxTotal} tsx`);
