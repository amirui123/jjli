#!/usr/bin/env node
/**
 * Splits the real source of every registry component into small, lazy-loadable
 * chunks so the browser never downloads 7 MB just to read one file.
 *
 *   toolkit/04-motion-primitives-and-ui/<registry>/**  ->  public/regcode/chunks/<registry>/<n>.json
 *   src/data/registryFiles.ts                          ->  sorted [path, bytes] per registry
 *
 * Chunk index is deterministic: floor(sortedIndex / CHUNK) — the client sorts
 * the same way, so no index payload is needed.
 */
import fs from "node:fs";
import path from "node:path";

const TOOLKIT_DIR = "toolkit";
if (!fs.existsSync(TOOLKIT_DIR) || fs.readdirSync(TOOLKIT_DIR).length < 4) {
  console.warn("[generate] toolkit/ missing — keeping committed data.");
  process.exit(0);
}

const ROOT = "toolkit/04-motion-primitives-and-ui";
if (!fs.existsSync(ROOT)) {
  console.warn("[generate] toolkit missing — skipping chunks.");
  process.exit(0);
}
const OUT = "public/regcode/chunks";
const CHUNK = 120;
const TEXT_EXT = new Set([".tsx", ".ts", ".jsx", ".js", ".css", ".json", ".md", ".mjs"]);
const MAX_FILE = 160_000;

const byCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function walk(dir, base = dir, acc = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "node_modules" || entry.name === ".git") continue;
      walk(full, base, acc);
    } else {
      acc.push(path.relative(base, full).split(path.sep).join("/"));
    }
  }
  return acc;
}

fs.rmSync(OUT, { recursive: true, force: true });

const registries = [];
let totalFiles = 0;
let totalChunks = 0;

for (const id of fs.readdirSync(ROOT).sort()) {
  const dir = path.join(ROOT, id);
  if (!fs.statSync(dir).isDirectory()) continue;

  const all = walk(dir).sort(byCodeUnit);
  const readable = all.filter((rel) => {
    const ext = path.extname(rel).toLowerCase();
    if (!TEXT_EXT.has(ext)) return false;
    return fs.statSync(path.join(dir, rel)).size <= MAX_FILE;
  });

  const files = all.map((rel) => {
    const size = fs.statSync(path.join(dir, rel)).size;
    return [rel, size];
  });

  let chunkCount = 0;
  for (let i = 0; i < readable.length; i += CHUNK) {
    const slice = readable.slice(i, i + CHUNK);
    const payload = slice.map((rel) => ({
      p: rel,
      s: fs.statSync(path.join(dir, rel)).size,
      c: fs.readFileSync(path.join(dir, rel), "utf8"),
    }));
    const outDir = path.join(OUT, id);
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(path.join(outDir, `${chunkCount}.json`), JSON.stringify(payload));
    chunkCount++;
  }

  const jsonFiles = all.filter((rel) => rel.toLowerCase().endsWith(".json")).length;
  const sourceFiles = all.length - jsonFiles;
  registries.push({
    id,
    totalFiles: all.length,
    sourceFiles,
    readable: readable.length,
    chunks: chunkCount,
    files,
  });
  totalFiles += all.length;
  totalChunks += chunkCount;
  console.log(
    `${id.padEnd(28)} ${String(all.length).padStart(5)} files · ${String(readable.length).padStart(5)} readable · ${chunkCount} chunks`
  );
}

const header = `/**
 * AUTO-GENERATED by scripts/generate-component-chunks.mjs — do not edit by hand.
 * ${registries.length} registries · ${totalFiles} files · ${totalChunks} lazy chunks.
 *
 * Paths are sorted with code-unit comparison, matching the generator, so the
 * client can compute chunk = floor(index / ${CHUNK}) without an index payload.
 */
export interface RegistryFiles {
  id: string;
  label: string;
  totalFiles: number;
  sourceFiles: number;
  readable: number;
  chunks: number;
  files: [string, number][];
}

export const CHUNK_SIZE = ${CHUNK};

export const REGISTRY_FILES: RegistryFiles[] = `;

const labels = {
  "animate-ui": "Animate UI",
  "cult-ui-registry": "Cult UI",
  "effect-ui": "Effect UI",
  "eldora-ui": "Eldora UI",
  "fancy-components": "Fancy",
  "kokonut-ui": "Kokonut UI",
  "magic-ui-registry": "Magic UI",
  "motion-primitives": "Motion Primitives",
  "persian-blocks-and-calendar": "بلوک‌های فارسی",
  "react-bits-ts-tailwind": "React Bits",
  "smooth-ui": "Smooth UI",
  "tailark-blocks": "Tailark",
};

const body = JSON.stringify(
  registries.map((r) => ({
    id: r.id,
    label: labels[r.id] ?? r.id,
    totalFiles: r.totalFiles,
    sourceFiles: r.sourceFiles,
    readable: r.readable,
    chunks: r.chunks,
    files: r.files,
  })),
  null,
  0
);

fs.mkdirSync("src/data", { recursive: true });
fs.writeFileSync("src/data/registryFiles.ts", `${header}${body};\n`);

const totalSource = registries.reduce((a, r) => a + r.sourceFiles, 0);
console.log(
  `\n✅ ${totalFiles} files (${totalSource} source) · ${totalChunks} chunks · src/data/registryFiles.ts`
);
