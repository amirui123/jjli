#!/usr/bin/env node
/**
 * Extracts the real font file behind every @font-face declaration so the
 * Font Studio can offer a genuine, downloadable font file per family.
 * Output: src/data/fontFiles.ts
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = "/home/user/jjli";
const CSS = fs.readFileSync(path.join(ROOT, "src/index.css"), "utf8");

const blocks = CSS.split("@font-face").slice(1);
const map = {};

for (const block of blocks) {
  const body = block.slice(0, block.indexOf("}"));
  const family = body.match(/font-family:\s*"([^"]+)"/)?.[1];
  const src = body.match(/src:\s*url\("(\/fonts\/[^"]+)"\)/)?.[1];
  const weight = body.match(/font-weight:\s*([^;]+);/)?.[1]?.trim() ?? "400";
  if (!family || !src) continue;
  if (map[family]) continue; // first declaration wins (matches CSS cascade order)
  const file = path.basename(src);
  const ext = path.extname(src).replace(".", "");
  map[family] = {
    url: src,
    file,
    ext,
    format: ext === "woff2" ? "woff2" : ext === "woff" ? "woff" : "truetype",
    weight,
  };
}

// Sanity: every file referenced must exist in public/
const missing = [];
for (const [family, info] of Object.entries(map)) {
  const abs = path.join(ROOT, "public", info.url.replace(/^\//, ""));
  if (!fs.existsSync(abs)) missing.push(`${family} → ${info.url}`);
}

const out = `/**
 * AUTO-GENERATED by scripts/generate-font-files.mjs — do not edit by hand.
 * Maps every @font-face family to its real, downloadable file in /public/fonts.
 */
export interface FontFileInfo {
  url: string;
  file: string;
  ext: string;
  format: string;
  weight: string;
}

export const FONT_FILE_BY_FAMILY: Record<string, FontFileInfo> = ${JSON.stringify(
  map,
  null,
  2
)};

export function fontFileFor(family: string): FontFileInfo | null {
  const first = family.split(",")[0].replace(/["']/g, "").trim();
  return FONT_FILE_BY_FAMILY[first] ?? null;
}
`;

fs.writeFileSync(path.join(ROOT, "src/data/fontFiles.ts"), out, "utf8");
console.log(
  `fontFiles.ts: ${Object.keys(map).length} families mapped` +
    (missing.length ? `\n⚠ missing files: ${missing.join(", ")}` : " — all files present")
);
