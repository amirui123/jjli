import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import pc from "picocolors";
import { requireProvider } from "../ai/resolve.js";
import type { ProviderOptions } from "../ai/provider.js";
import type { ParsedTarget } from "../util/detect-url.js";
import { run } from "../util/shell.js";
import { confirm, log, spinner } from "../util/ui.js";
import { runServer } from "../repo/run.js";
import { captureSite, type Capture } from "./capture.js";
import { generateProject } from "./generate.js";

export interface SiteOptions extends ProviderOptions {
  dir?: string;
  yes: boolean;
  open: boolean;
  sanitize: boolean;
  /** Only capture: write the capture JSON + screenshots and stop. */
  captureOnly: boolean;
}

export async function reverseEngineerAndRun(target: ParsedTarget, opts: SiteOptions): Promise<void> {
  const total = 5;
  const dest = path.resolve(opts.dir ?? target.name);
  const provider = opts.captureOnly ? null : requireProvider(opts);

  if (existsSync(dest) && existsSync(path.join(dest, "package.json")) && !opts.yes) {
    const go = await confirm(`${dest} already has a project. Overwrite the generated files?`, false);
    if (!go) return;
  }
  mkdirSync(path.join(dest, ".breakinggood"), { recursive: true });

  // 1. capture
  log.step(1, total, `Reverse-engineer ${pc.cyan(target.url)}`);
  const sp = spinner("launching your Chrome/Edge headless…");
  let cap: Capture;
  try {
    cap = await captureSite(target.url, { log: (m) => (sp.text = m) });
    sp.succeed(
      `captured: ${cap.outline.length} landmarks, ${cap.links.length} links, ${cap.images.length} images, ` +
        `${cap.requests.length} API calls, fonts ${cap.tokens.fonts.slice(0, 2).join("/") || "?"}`,
    );
  } catch (e) {
    sp.fail("capture failed");
    throw e;
  }
  if (cap.fingerprints.length) log.dim("original stack fingerprints: " + cap.fingerprints.join(", "));
  saveCapture(dest, cap);
  log.dim(`capture saved to ${path.relative(process.cwd(), path.join(dest, ".breakinggood"))}/`);
  if (opts.captureOnly) return;

  // 2. generate
  log.step(2, total, `Rebuild with ${pc.bold(provider!.name)} ${pc.dim(provider!.model)}`);
  if (!provider!.supportsImages) log.warn("this provider has no vision — generating from DOM + tokens only");
  const gen = spinner("writing the project…");
  let chars = 0;
  let files: Map<string, string>;
  try {
    files = await generateProject(provider!, cap, target.name, {
      sanitize: opts.sanitize,
      onChunk: (t) => {
        chars += t.length;
        gen.text = `writing the project… ${(chars / 1000).toFixed(0)}k chars`;
      },
    });
    gen.succeed(`generated ${files.size} files`);
  } catch (e) {
    gen.fail("generation failed");
    throw e;
  }

  // 3. write
  log.step(3, total, "Write project");
  files.set(
    "README.md",
    (files.get("README.md") ?? `# ${target.name}\n`) +
      `\n---\n\nRebuilt from ${cap.url} with [breakinggood](https://github.com/eklavya2201/breakinggood) — \`npx breakinggood <url>\`.\n`,
  );
  for (const [rel, content] of files) {
    const full = path.join(dest, rel);
    mkdirSync(path.dirname(full), { recursive: true });
    writeFileSync(full, content);
    log.dim(rel);
  }
  // Always add the provenance note.
  writeFileSync(
    path.join(dest, ".breakinggood", "PROVENANCE.md"),
    `Generated by breakinggood from ${cap.url} on ${new Date().toISOString()} using ${provider!.name}/${provider!.model}.\n` +
      `This is a reconstruction for learning/prototyping. The original site's content, trademarks and images belong to their owners.\n`,
  );
  log.ok(`written to ${pc.bold(path.relative(process.cwd(), dest))}`);

  // 4. install
  log.step(4, total, "Install");
  const res = await run("npm", ["install", "--no-audit", "--no-fund", "--loglevel=error"], { cwd: dest, quiet: true });
  if (res.code !== 0) throw new Error("npm install failed:\n" + res.output.slice(-2000));
  log.ok("installed");

  // 5. run
  log.step(5, total, "Run");
  await runServer(dest, { cmd: "npm", args: ["run", "dev"], label: "npm run dev" }, { open: opts.open, knownPorts: [5173] });
}

function saveCapture(dest: string, cap: Capture): void {
  const dir = path.join(dest, ".breakinggood");
  cap.screenshotsDesktop.forEach((b, i) => writeFileSync(path.join(dir, `desktop-${i + 1}.jpg`), Buffer.from(b, "base64")));
  cap.screenshotsMobile.forEach((b, i) => writeFileSync(path.join(dir, `mobile-${i + 1}.jpg`), Buffer.from(b, "base64")));
  const { screenshotsDesktop: _d, screenshotsMobile: _m, ...rest } = cap;
  writeFileSync(path.join(dir, "capture.json"), JSON.stringify(rest, null, 2));
}
